def apply_comments(clear=False):
    connection = op.get_bind()
    if connection.dialect.name != "mysql":
        return
    inspector = sa.inspect(connection)
    # Validate the entire frozen catalog before the first nontransactional MySQL DDL.
    columns_by_table = {}
    tables = set(inspector.get_table_names())
    for name, (_, expected_columns) in COMMENTS.items():
        if name not in tables:
            raise RuntimeError(f"Missing table for schema comments: {name}")
        columns = {column["name"]: column for column in inspector.get_columns(name)}
        missing = expected_columns.keys() - columns.keys()
        if missing:
            raise RuntimeError(f"Missing columns for schema comments: {name}: {sorted(missing)}")
        columns_by_table[name] = columns

    for name, (table_comment, comments) in COMMENTS.items():
        existing_comment = inspector.get_table_comment(name)["text"] or ""
        if not clear or existing_comment == table_comment:
            op.create_table_comment(
                name, "" if clear else table_comment, existing_comment=existing_comment
            )
        for column_name, comment in comments.items():
            column = columns_by_table[name][column_name]
            if clear and column.get("comment") != comment:
                continue
            default = column["default"]
            op.alter_column(
                name,
                column_name,
                comment="" if clear else comment,
                existing_comment=column.get("comment"),
                existing_type=column["type"],
                existing_nullable=column["nullable"],
                existing_server_default=sa.text(default) if default is not None else None,
                existing_autoincrement=column.get("autoincrement", False),
            )


def upgrade():
    apply_comments()


def downgrade():
    # Preserve comments manually revised after this migration.
    apply_comments(clear=True)
