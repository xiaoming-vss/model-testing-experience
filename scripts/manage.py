#!/usr/bin/env python3
"""Unified configuration and launch commands; requires Python 3.11+ only."""

from __future__ import annotations

import argparse
import copy
import json
import os
from pathlib import Path
import re
import secrets
import subprocess
import sys
import tempfile
import tomllib
from urllib.parse import quote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
PROJECTS = {
    "control-plane": "apps/control-plane",
    "ai-worker": "apps/ai-worker",
    "api-ui-worker": "apps/api-ui-worker",
    "integration-worker": "apps/integration-worker",
    "studio": "apps/studio",
}


def merge(base, override):
    result = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = merge(result[key], value)
        else:
            result[key] = copy.deepcopy(value)
    return result


def toml_text(data):
    lines = ["# Generated by scripts/manage.py; edit config/platform.toml instead."]

    def scalar(value):
        if isinstance(value, bool):
            return str(value).lower()
        if isinstance(value, str):
            return json.dumps(value, ensure_ascii=False)
        if isinstance(value, (int, float)):
            return repr(value)
        if isinstance(value, list):
            return "[" + ", ".join(scalar(item) for item in value) + "]"
        raise ValueError(f"Unsupported TOML value type: {type(value).__name__}")

    def emit(table, path):
        if path:
            lines.extend(["", "[" + ".".join(json.dumps(k) for k in path) + "]"])
        for key, value in table.items():
            if not isinstance(value, dict):
                lines.append(f"{json.dumps(key)} = {scalar(value)}")
        for key, value in table.items():
            if isinstance(value, dict):
                emit(value, path + [key])

    emit(data, [])
    return "\n".join(lines) + "\n"


def read(path):
    with path.open("rb") as stream:
        return tomllib.load(stream)


def write(path, content, *, container=False, permissions=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    # Atomic replacement prevents readers seeing a partly generated file.
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        prefix=path.name + ".",
        suffix=".tmp",
        delete=False,
    ) as stream:
        temp = Path(stream.name)
        stream.write(content)
    try:
        temp.chmod(permissions if permissions is not None else (0o644 if container else 0o600))
        temp.replace(path)
    finally:
        temp.unlink(missing_ok=True)


def _generate_nested(value):
    if isinstance(value, dict):
        return {key: _generate_nested(item) for key, item in value.items()}
    if value == "GENERATE":
        return secrets.token_hex(32)
    return value


def init(root=ROOT):
    path = root / "config/platform.toml"
    if path.exists():
        print("Existing config/platform.toml preserved.")
        return
    data = _generate_nested(read(root / "config/platform.example.toml"))
    write(path, toml_text(data))
    print("Created config/platform.toml with fresh local credentials.")


def upgrade_config(root=ROOT):
    """Add newer settings while preserving existing values and file mode."""
    path = root / "config/platform.toml"
    if not path.exists():
        init(root)
        return
    data = read(path)
    original = copy.deepcopy(data)
    shared = data.setdefault("shared", {})
    for key in ("integration_worker_token", "integration_runtime_generation"):
        if key not in shared or shared[key] == "GENERATE":
            value = secrets.token_hex(32)
            while value in shared.values():
                value = secrets.token_hex(32)
            shared[key] = value
    example_control_plane = read(root / "config/platform.example.toml").get(
        "control_plane", {}
    )
    defaults = example_control_plane["integration_execution"]
    settings = data.setdefault("control_plane", {}).setdefault("integration_execution", {})
    for key, value in defaults.items():
        settings.setdefault(key, copy.deepcopy(value))
    security_defaults = example_control_plane.get("security", {})
    security = data.setdefault("control_plane", {}).setdefault("security", {})
    for section in ("super_admin", "login", "jwt"):
        target = security.setdefault(section, {})
        for key, value in security_defaults.get(section, {}).items():
            target.setdefault(key, copy.deepcopy(value))
        for key, value in list(target.items()):
            if value == "GENERATE":
                target[key] = secrets.token_hex(16)
    if data == original:
        print("Unified configuration already has current settings.")
        return
    validate(data)
    write(path, toml_text(data), permissions=path.stat().st_mode & 0o777)
    print("Added missing settings; existing credentials preserved.")


def external_database_url(data):
    """Return a validated async MySQL URL without logging its credentials."""
    raw = data["database"].get("url", "")
    if not isinstance(raw, str):
        raise ValueError("database.url must be a string")
    raw = raw.strip()
    if not raw:
        return ""
    error = "database.url must be mysql+asyncmy://user:password@host:port/database (URL-encode special characters)"
    try:
        parsed = urlsplit(raw)
        valid = (
            parsed.scheme in ("mysql", "mysql+asyncmy")
            and parsed.hostname
            and parsed.username
            and parsed.path not in ("", "/")
            and not parsed.fragment
            and not any(char.isspace() for char in raw)
            and (parsed.port is None or 1 <= parsed.port <= 65535)
        )
    except ValueError:
        raise ValueError(error) from None
    if not valid:
        raise ValueError(error)
    if parsed.scheme == "mysql":
        return "mysql+asyncmy://" + raw.split("://", 1)[1]
    return raw


def mysql_observability(data):
    database = data["database"]
    enabled = database.get("slow_query_log", True)
    threshold = database.get("long_query_time", 0.5)
    if type(enabled) is not bool:
        raise ValueError("database.slow_query_log must be a boolean")
    if type(threshold) not in (int, float) or not 0.01 <= threshold <= 3600:
        raise ValueError("database.long_query_time must be between 0.01 and 3600 seconds")
    return {"MYSQL_SLOW_QUERY_LOG": int(enabled), "MYSQL_LONG_QUERY_TIME": threshold}


def validate(data):
    shared, db = data["shared"], data["database"]
    external = bool(external_database_url(data))
    mysql_observability(data)
    for key in ("worker_token", "jwt_key", "integration_key"):
        if not shared[key] or shared[key] == "GENERATE":
            raise ValueError(f"Set shared.{key}, or run init first")
    for key in ("integration_worker_token", "integration_runtime_generation"):
        if not shared.get(key) or shared[key] == "GENERATE":
            raise ValueError(f"Set shared.{key}, or run upgrade-config for an existing deployment")
    if shared["integration_worker_token"] == shared["worker_token"]:
        raise ValueError("The integration Worker token must differ from shared.worker_token")
    super_admin = (
        data.get("control_plane", {})
        .get("security", {})
        .get("super_admin", {})
    )
    if not super_admin.get("username") or not super_admin.get("email"):
        raise ValueError(
            "control_plane.security.super_admin.username and email are required"
        )
    if not external:
        for key in ("password", "root_password"):
            if not db.get(key) or db[key] == "GENERATE":
                raise ValueError(f"Set database.{key}, or run init first")
        for key in ("name", "user"):
            if not re.fullmatch(r"[A-Za-z0-9_]+", db.get(key, "")):
                raise ValueError(
                    f"database.{key} must contain letters, digits or underscores"
                )
        if db["user"] == "root":
            raise ValueError("database.user must be a non-root application user")
    for key in ("public_host", "local_host", "bind_host"):
        if not re.fullmatch(r"[A-Za-z0-9_.-]+", shared[key]):
            raise ValueError(
                f"shared.{key} must be an IPv4 address or hostname without a port"
            )
    port_keys = ["studio_port", "control_plane_port"]
    if not external:
        port_keys.append("mysql_port")
    ports = [shared[k] for k in port_keys]
    if any(type(p) is not int or not 1 <= p <= 65535 for p in ports) or len(
        set(ports)
    ) != len(ports):
        raise ValueError("Service ports must be distinct integers between 1 and 65535")


def configurations(data, mode, root=ROOT):
    validate(data)
    s, db = data["shared"], data["database"]
    docker = mode == "docker"
    host = s["local_host"]
    cp_url = (
        "http://control-plane:9000"
        if docker
        else f"http://{host}:{s['control_plane_port']}"
    )
    dsn = external_database_url(data)
    if not dsn:
        db_host = "mysql" if docker else host
        db_port = 3306 if docker else s["mysql_port"]
        dsn = f"mysql+asyncmy://{quote(db['user'], safe='')}:{quote(db['password'], safe='')}@{db_host}:{db_port}/{db['name']}?charset=utf8mb4"
    specs = {
        "control-plane": ("config/local.example.toml", "control_plane"),
        "ai-worker": ("config/worker.example.toml", "ai_worker"),
        "api-ui-worker": ("config.example.toml", "api_ui_worker"),
        "integration-worker": ("config/local.example.toml", "integration_worker"),
    }
    result = {
        name: merge(read(root / PROJECTS[name] / file), data.get(section, {}))
        for name, (file, section) in specs.items()
    }
    result["control-plane"] = merge(
        result["control-plane"],
        {
            "env": "production" if docker else "local",
            "http": {
                "host": "0.0.0.0" if docker else host,
                "port": 9000 if docker else s["control_plane_port"],
            },
            "security": {
                "jwt": {"key": s["jwt_key"]},
                "integration": {"key": s["integration_key"]},
                "worker": {"key": s["worker_token"]},
                "integration_worker": {"key": s["integration_worker_token"]},
            },
            "integration_execution": {"runtime_generation": s["integration_runtime_generation"]},
            "data": {"db": {"user": {"dsn": dsn}}},
        },
    )
    result["control-plane"].setdefault("security", {}).pop("ldap", None)
    result["ai-worker"] = merge(
        result["ai-worker"],
        {
            "platform": {"base_url": cp_url, "worker_token": s["worker_token"]},
            "nanobot": {"runtime_root": "/data/runtime" if docker else "runtime"},
            "logging": {"dir": "/app/logs" if docker else "logs"},
        },
    )
    result["api-ui-worker"] = merge(
        result["api-ui-worker"],
        {
            "control_plane": {"base_url": cp_url, "worker_token": s["worker_token"]},
            "ui": {
                "artifacts_dir": "/app/artifacts" if docker else "artifacts",
            },
        },
    )
    result["integration-worker"] = merge(result["integration-worker"], {
        "control_plane": {"base_url": cp_url, "worker_token": s["integration_worker_token"]},
        "worker": {"health_file": "/app/runtime/health.json" if docker else "runtime/health.json",
                   "evidence_file": "/app/runtime/evidence.json" if docker else "runtime/evidence.json"},
    })
    return result


def env_text(values):
    # Compose and Vite dotenv both preserve literal dollars in single quotes.
    return "".join(
        key + "='" + str(value).replace("'", "\\'") + "'\n"
        for key, value in values.items()
    )


def configure(mode, root=ROOT):
    data = read(root / "config/platform.toml")
    configs = configurations(data, mode, root)
    runtime = root / ".runtime"
    runtime.mkdir(exist_ok=True)
    runtime.chmod(0o700)
    local_files = {
        "control-plane": "config/local.toml",
        "ai-worker": "config/worker.toml",
        "api-ui-worker": "config.toml",
        "integration-worker": "config/local.toml",
    }
    for name, config in configs.items():
        path = (
            runtime / "docker" / f"{name}.toml"
            if mode == "docker"
            else root / PROJECTS[name] / local_files[name]
        )
        write(path, toml_text(config), container=mode == "docker")
    s, db = data["shared"], data["database"]
    if mode == "docker":
        env = {
            k.upper(): s[k]
            for k in (
                "bind_host",
                "studio_port",
                "control_plane_port",
            )
        }
        env["MYSQL_PORT"] = s.get("mysql_port", 13306)
        env.update(mysql_observability(data))
        if external_database_url(data):
            # Compose interpolates the base file before !reset removes mysql.
            # These placeholders are never used by a running service.
            env.update(
                {
                    key: "unused-external-database"
                    for key in (
                        "MYSQL_DATABASE",
                        "MYSQL_USER",
                        "MYSQL_PASSWORD",
                        "MYSQL_ROOT_PASSWORD",
                    )
                }
            )
        else:
            env.update(
                MYSQL_DATABASE=db["name"],
                MYSQL_USER=db["user"],
                MYSQL_PASSWORD=db["password"],
                MYSQL_ROOT_PASSWORD=db["root_password"],
            )
        write(runtime / "compose.env", env_text(env))
        (runtime / "compose.ldap-ca.json").unlink(missing_ok=True)
    else:
        write(
            root / PROJECTS["studio"] / ".env.local",
            env_text(
                {
                    "VITE_API_PROXY_TARGET": f"http://{s['local_host']}:{s['control_plane_port']}"
                }
            ),
        )
    print(f"Generated {mode} configuration.")


def compose_command(root=ROOT):
    command = [
        "docker",
        "compose",
        "--project-directory",
        str(root),
        "--env-file",
        str(root / ".runtime/compose.env"),
        "-f",
        str(root / "compose.yaml"),
    ]
    if external_database_url(read(root / "config/platform.toml")):
        command.extend(["-f", str(root / "deploy/compose.external-db.yaml")])
    ca_override = root / ".runtime/compose.ldap-ca.json"
    if ca_override.exists():
        command.extend(["-f", str(ca_override)])
    return command


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    sub.add_parser(
        "init", help="Create unified local config without replacing an existing one"
    )
    sub.add_parser("upgrade-config", help="Add missing integration settings without rotating secrets")
    config = sub.add_parser("configure", help="Generate service configuration")
    config.add_argument("--mode", choices=["local", "docker"], default="docker")
    run = sub.add_parser(
        "run", help="Run one service locally; install its dependencies first"
    )
    run.add_argument("service", choices=PROJECTS)
    sub.add_parser(
        "migrate", help="Apply database migrations using local configuration"
    )
    compose = sub.add_parser(
        "compose",
        help="Generate Docker config and forward remaining args to Docker Compose",
    )
    compose.add_argument("args", nargs=argparse.REMAINDER)
    argv = sys.argv[1:]
    args = parser.parse_args(["compose"] if argv[:1] == ["compose"] else argv)
    if args.action == "compose":
        args.args = argv[1:]
    if args.action == "init":
        init()
        return
    if args.action == "upgrade-config":
        upgrade_config()
        return
    if args.action == "configure":
        configure(args.mode)
        return
    if args.action == "compose":
        configure("docker")
        raise SystemExit(subprocess.call(compose_command() + args.args, cwd=ROOT))
    configure("local")
    name = "control-plane" if args.action == "migrate" else args.service
    commands = {
        "control-plane": ["uv", "run", "--locked", "mtx-control-plane"],
        "ai-worker": ["uv", "run", "--locked", "mtx-ai-worker"],
        "api-ui-worker": ["uv", "run", "--locked", "mtx-api-ui-worker"],
        "integration-worker": ["uv", "run", "--locked", "mtx-integration-worker"],
        "studio": ["npm", "run", "dev"],
    }
    command = (
        ["uv", "run", "--locked", "alembic", "upgrade", "head"]
        if args.action == "migrate"
        else commands[name]
    )
    env = os.environ.copy()
    if name in {"control-plane", "integration-worker"}:
        env["APP_CONF"] = str(ROOT / PROJECTS[name] / "config/local.toml")
    raise SystemExit(subprocess.call(command, cwd=ROOT / PROJECTS[name], env=env))


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, FileNotFoundError, tomllib.TOMLDecodeError) as exc:
        print(f"Configuration error: {exc}", file=sys.stderr)
        raise SystemExit(2) from None
